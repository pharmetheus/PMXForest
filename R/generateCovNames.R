#' Generate and Format Covariate Labels for Forest Plots
#'
#' @description
#' Dynamically constructs covariate names from a forest plot covariate data frame.
#' If \code{dfres} is provided, it safely maps these generated labels directly onto the
#' results data frame using the \code{COVNUM} relational key, returning the updated data frame.
#'
#' It features an interactive two-step workflow: run with \code{print_template = TRUE}
#' to generate a boilerplate mapping script in the console, then fill it out and
#' pass the maps back in to append units, replace categorical labels, or format group headers.
#'
#' With \code{name_map}, a covariate is named once and that name is used in every
#' row label and in the group header: \code{name_map = c(WTKGBL = "Weight")} and
#' \code{unit_map = c(WTKGBL = "kg")} label the rows \code{"Weight = 58.3 kg"} and
#' \code{"Weight = 126 kg"}, whatever percentiles the data give, and head the group
#' \code{"Weight"}. Without \code{name_map} the labels are \code{"WTKGBL=58.3 kg"}, as
#' before.
#'
#' @param dfCovs A data frame containing covariate scenarios (must have a \code{COVARIATEGROUPS} column).
#' @param dfres An optional results data frame generated by [getForestDFSCM()] or
#'   [getForestDFemp()], or by `PMXFrem::getForestDFFREM()`. If provided, the function
#'   returns this data frame with the \code{COVNAME} and \code{GROUPNAME} columns updated
#'   and safely factored.
#' @param unit_map A named character vector for appending units (e.g., \code{c(WT = "kg")}).
#' @param label_map A named character vector for exact replacements (e.g., \code{c("SEX=1" = "Male")}).
#' @param group_map A named character vector for replacing covariate group names
#'   (e.g., \code{c("WT" = "Weight", "SEX" = "Sex")}). A group not in \code{group_map}
#'   takes its name from \code{name_map}, so \code{group_map} is only needed when the
#'   group header should differ from the name in the row labels.
#' @param print_template Logical. If \code{TRUE}, prints an R script template to the console and exits.
#' @param name_map A named character vector of display names for the covariates
#'   (e.g., \code{c(WTKGBL = "Weight", SEXN = "Sex")}). When given, every row not
#'   matched by \code{label_map} is labelled with \code{label_format}, using the
#'   display name in place of the column name; covariates missing from it keep their
#'   column name. It also names the groups, see \code{group_map}.
#' @param label_format The row label used with \code{name_map}. `{name}`, `{value}`
#'   and `{unit}` are replaced by the display name, the covariate value and the
#'   \code{unit_map} entry. Defaults to `"{name} = {value} {unit}"`; the space before
#'   an empty unit is dropped.
#'
#' @return If \code{dfres} is \code{NULL}, returns a character vector of formatted covariate names.
#'   If \code{dfres} is provided, returns the updated \code{dfres} data frame containing factored
#'   \code{COVNAME} and \code{GROUPNAME} columns.
#'
#' @seealso [setupDfCovs()] for the covariate table, [forestPlot()] for the plot.
#' @export
#'
#' @examples
#' # 1. Create a synthetic forest plot covariate dataframe
#' dfCovs <- data.frame(
#'   COVARIATEGROUPS = c("WT", "WT", "SEX", "SEX"),
#'   WT = c(70, 90, -99, -99),
#'   SEX = c(-99, -99, 1, 2)
#' )
#'
#' # 2. Create a synthetic results dataframe
#' dfres <- data.frame(
#'   COVNUM = c(1, 2, 3, 4),
#'   PARAMETER = rep("CL", 4),
#'   VALUE = c(1.1, 1.3, 0.9, 1.0)
#' )
#'
#' # 3. Define Translation Maps
#' name_map <- c(WT = "Body Weight", SEX = "Sex")
#' unit_map <- c(WT = "kg")
#' label_map <- c("SEX=1" = "Male", "SEX=2" = "Female")
#' group_map <- c("WT" = "Body Weight", "SEX" = "Biological Sex")
#'
#' # --- Example A: Extract Character Vector ---
#' # Returns standard formatted strings for covariate names
#' generateCovNames(dfCovs, unit_map = unit_map, label_map = label_map)
#'
#' # --- Example B: Relational Data Frame Mapping ---
#' # Safely mutates the data frame, adding locked COVNAME and GROUPNAME factors
#' dfres_updated <- generateCovNames(
#'   dfCovs,
#'   dfres = dfres,
#'   unit_map = unit_map,
#'   label_map = label_map,
#'   group_map = group_map
#' )
#'
#' print(dfres_updated)
#'
#' # --- Example C: Name each covariate once ---
#' # Rows read "Body Weight = 70 kg"; the groups are "Body Weight" and "Sex"
#' generateCovNames(
#'   dfCovs,
#'   dfres = dfres,
#'   name_map = name_map,
#'   unit_map = unit_map,
#'   label_map = label_map
#' )
generateCovNames <- function(dfCovs, dfres = NULL, unit_map = NULL, label_map = NULL, group_map = NULL,
                             print_template = FALSE, name_map = NULL,
                             label_format = "{name} = {value} {unit}") {
  if (!"COVARIATEGROUPS" %in% names(dfCovs)) {
    stop("dfCovs must contain a 'COVARIATEGROUPS' column.", call. = FALSE)
  }

  # 1. Extract the covariate value of each row, and the base strings and groups
  groups <- as.character(dfCovs$COVARIATEGROUPS)
  values <- sapply(seq_len(nrow(dfCovs)), function(i) {
    grp <- groups[i]

    if (grp %in% names(dfCovs)) {
      return(as.character(dfCovs[[grp]][i]))
    }

    pattern <- paste0("^", grp, "_")
    dummy_cols <- grep(pattern, names(dfCovs), value = TRUE)

    if (length(dummy_cols) == 0) {
      warning(paste("No matching columns found for covariate group:", grp), call. = FALSE)
      return("UNKNOWN")
    }

    suffixes <- as.numeric(gsub(pattern, "", dummy_cols))
    row_vals <- as.numeric(dfCovs[i, dummy_cols, drop = FALSE])

    if (any(row_vals == 1, na.rm = TRUE)) {
      val <- suffixes[which(row_vals == 1)[1]]
    } else {
      val <- min(suffixes, na.rm = TRUE) - 1
    }
    return(as.character(val))
  })
  base_strings <- paste0(groups, "=", values)

  # 2. Template Generation Mode
  if (print_template) {
    u_groups <- unique(groups)
    u_base <- unique(base_strings)

    cat("# Copy and paste this mapping template into your script:\n\n")

    cat("group_map <- c(\n")
    cat(paste0("  \"", u_groups, "\" = \"\""), sep = ",\n")
    cat("\n)\n\n")

    cat("unit_map <- c(\n")
    cat(paste0("  \"", u_groups, "\" = \"\""), sep = ",\n")
    cat("\n)\n\n")

    cat("label_map <- c(\n")
    cat(paste0("  \"", u_base, "\" = \"\""), sep = ",\n")
    cat("\n)\n")

    return(invisible(NULL))
  }

  # 3. Application Mode (Row-level labels)
  res <- sapply(seq_along(base_strings), function(i) {
    b <- base_strings[i]
    g <- groups[i]

    # Label Replacement (Categorical) takes precedence
    if (!is.null(label_map) && b %in% names(label_map)) {
      if (label_map[[b]] != "") {
        return(label_map[[b]])
      }
    }

    # Display name, value and unit
    if (!is.null(name_map)) {
      return(formatCovLabel(label_format, mapEntry(name_map, g, g), values[i], mapEntry(unit_map, g, "")))
    }

    # Unit Appending (Continuous)
    if (!is.null(unit_map) && g %in% names(unit_map)) {
      if (unit_map[[g]] != "") {
        return(paste0(b, " ", unit_map[[g]]))
      }
    }

    return(b)
  })

  # 4. Relational Data Frame Mapping
  if (!is.null(dfres)) {
    if (!"COVNUM" %in% names(dfres)) {
      stop("The provided dfres must contain a 'COVNUM' column to securely map the labels.", call. = FALSE)
    }

    # Map the row labels securely using the row index indicator
    mapped_labels <- res[dfres$COVNUM]
    dfres$COVNAME <- factor(mapped_labels, levels = unique(res))

    # Map the group headers securely
    mapped_groups <- sapply(groups, function(g) {
      return(mapEntry(group_map, g, mapEntry(name_map, g, g)))
    })

    # Apply as a factor to lock the group plotting order
    mapped_groups_expanded <- mapped_groups[dfres$COVNUM]
    dfres$GROUPNAME <- factor(mapped_groups_expanded, levels = unique(mapped_groups))

    return(dfres)
  }

  return(as.character(res))
}

## The entry for key in a named map, or default when the map is NULL, has no
## such key, or holds "" for it - a blank entry in a printed template.
mapEntry <- function(map, key, default) {
  if (!is.null(map) && key %in% names(map) && map[[key]] != "") {
    return(map[[key]])
  }
  return(default)
}

## Fill the {name}, {value} and {unit} placeholders of a label format. Without
## a unit, the space before the placeholder is dropped as well.
formatCovLabel <- function(format, name, value, unit) {
  out <- format
  if (unit == "") {
    out <- gsub("\\s*\\{unit\\}", "", out)
  }
  out <- gsub("{name}", name, out, fixed = TRUE)
  out <- gsub("{value}", value, out, fixed = TRUE)
  out <- gsub("{unit}", unit, out, fixed = TRUE)
  return(out)
}
