#' Generate and Format Covariate Labels for Forest Plots
#'
#' @description
#' Dynamically constructs covariate names from a forest plot covariate data frame.
#' If \code{dfres} is provided, it safely maps these generated labels directly onto the
#' results data frame using the \code{COVNUM} relational key, returning the updated data frame.
#'
#' It features an interactive two-step workflow: run with \code{print_template = TRUE}
#' to generate a boilerplate mapping script in the console, then fill it out and
#' pass the maps back in to append units, replace categorical labels, or format group headers.
#'
#' With \code{name_map}, a covariate is named once and that name is used in every
#' row label and in the group header: \code{name_map = c(WTKGBL = "Weight")} and
#' \code{unit_map = c(WTKGBL = "kg")} label the rows \code{"Weight = 58.3 kg"} and
#' \code{"Weight = 126 kg"}, whatever percentiles the data give, and head the group
#' \code{"Weight"}. Without \code{name_map} the labels are \code{"WTKGBL=58.3 kg"}, as
#' before.
#'
#' Categorical levels are named per covariate with \code{level_map}, e.g.
#' \code{level_map = list(SEXN = c("1" = "Male", "2" = "Female"))}. A level set to
#' \code{NA} drops its row from the plot.
#'
#' A set of 0/1 dummy covariates that together code one categorical covariate, such
#' as \code{GENO1N}, \code{GENO3N} and \code{GENO4N} against a common reference
#' genotype, is merged into one group with \code{dummy_groups}. Each dummy's
#' \code{1} row is labelled with its level, and the \code{0} rows - one per dummy, all
#' at the shared reference - become a single reference row. As the group is one
#' \code{GROUPNAME}, \code{onlySignificant} in [forestPlot()] shows or hides it as a
#' whole.
#'
#' Every map is checked: a key given twice is an error, and with \code{warn_unused}, a
#' key that matches no covariate or level in \code{dfCovs} - a typo, or a value that
#' has changed with the data - is warned about rather than silently ignored.
#'
#' A row's label is taken from the first of these that gives one: \code{label_map},
#' \code{dummy_groups}, \code{level_map}, \code{name_map} with \code{label_format},
#' and finally the column name and value, with the \code{unit_map} unit appended.
#'
#' @param dfCovs A data frame containing covariate scenarios (must have a \code{COVARIATEGROUPS} column).
#' @param dfres An optional results data frame generated by [getForestDFSCM()] or
#'   [getForestDFemp()], or by `PMXFrem::getForestDFFREM()`. If provided, the function
#'   returns this data frame with the \code{COVNAME} and \code{GROUPNAME} columns updated
#'   and safely factored.
#' @param unit_map A named character vector for appending units (e.g., \code{c(WT = "kg")}).
#' @param label_map A named character vector for exact replacements (e.g., \code{c("SEX=1" = "Male")}).
#'   An \code{NA} entry drops the row, as in \code{level_map}.
#' @param group_map A named character vector for replacing covariate group names
#'   (e.g., \code{c("WT" = "Weight", "SEX" = "Sex")}). A group not in \code{group_map}
#'   takes its name from \code{name_map}, so \code{group_map} is only needed when the
#'   group header should differ from the name in the row labels.
#' @param print_template Logical. If \code{TRUE}, prints an R script template to the console and exits.
#'   The template has a \code{name_map} entry per covariate, a \code{unit_map} entry per
#'   continuous covariate and a \code{level_map} entry per categorical one. Whether a
#'   covariate is categorical is guessed from \code{dfCovs} (one-hot encoded, or only
#'   integer values from 0 to 9), so check the two lists. Blank entries are ignored,
#'   so the template can be passed back before it is filled in.
#' @param name_map A named character vector of display names for the covariates
#'   (e.g., \code{c(WTKGBL = "Weight", SEXN = "Sex")}). When given, every row not
#'   matched by \code{label_map} is labelled with \code{label_format}, using the
#'   display name in place of the column name; covariates missing from it keep their
#'   column name. It also names the groups, see \code{group_map}.
#' @param label_format The row label used with \code{name_map}. `{name}`, `{value}`
#'   and `{unit}` are replaced by the display name, the covariate value and the
#'   \code{unit_map} entry. Defaults to `"{name} = {value} {unit}"`; the space before
#'   an empty unit is dropped.
#' @param level_map A named list with one entry per categorical covariate: a vector
#'   of labels named by level, e.g.
#'   \code{list(SEXN = c("1" = "Male", "2" = "Female"), FOODDN = c("0" = "Fasted", "1" = "Fed"))}.
#'   A mapped level is labelled with its label alone. A level left out, or set to
#'   \code{""}, falls through to \code{name_map}, e.g. \code{"Sex = 1"}. A level set
#'   to \code{NA} drops the row.
#' @param dummy_groups A named list merging 0/1 dummy covariates into one group each.
#'   The name is the group header, and each entry is a list with \code{levels}, the
#'   label of each dummy's \code{1} row named by the dummy, and \code{ref}, the label
#'   of the single reference row kept from the dummies' \code{0} rows, e.g.
#'   \code{list("2D6 genotype" = list(ref = "2D6 EM", levels = c(GENO1N = "2D6 UM",
#'   GENO3N = "2D6 IM", GENO4N = "2D6 PM")))}. Leave \code{ref} out, or set it to
#'   \code{NA}, to drop the reference row as well.
#' @param sep The separator between the covariate name and the level in the one-hot
#'   column names, as given to [setupDfCovs()]. When left out, it is read from
#'   \code{dfCovs} if [setupDfCovs()] made it, and is \code{"_"} otherwise.
#' @param warn_unused Logical. Warn about map keys that match no covariate or level in
#'   \code{dfCovs}? Defaults to \code{TRUE}; set it to \code{FALSE} when sharing one set
#'   of maps between models with different covariates.
#'
#' @return If \code{dfres} is \code{NULL}, returns a character vector of formatted covariate names,
#'   one per row of \code{dfCovs}, with \code{NA} for a dropped row.
#'   If \code{dfres} is provided, returns the updated \code{dfres} data frame containing factored
#'   \code{COVNAME} and \code{GROUPNAME} columns, without the rows of dropped levels.
#'
#' @seealso [setupDfCovs()] for the covariate table, [forestPlot()] for the plot.
#' @export
#'
#' @examples
#' # 1. Create a synthetic forest plot covariate dataframe
#' dfCovs <- data.frame(
#'   COVARIATEGROUPS = c("WT", "WT", "SEX", "SEX"),
#'   WT = c(70, 90, -99, -99),
#'   SEX = c(-99, -99, 1, 2)
#' )
#'
#' # 2. Create a synthetic results dataframe
#' dfres <- data.frame(
#'   COVNUM = c(1, 2, 3, 4),
#'   PARAMETER = rep("CL", 4),
#'   VALUE = c(1.1, 1.3, 0.9, 1.0)
#' )
#'
#' # 3. Define Translation Maps
#' name_map <- c(WT = "Body Weight", SEX = "Sex")
#' level_map <- list(SEX = c("1" = "Male", "2" = "Female"))
#' unit_map <- c(WT = "kg")
#' label_map <- c("SEX=1" = "Male", "SEX=2" = "Female")
#' group_map <- c("WT" = "Body Weight", "SEX" = "Biological Sex")
#'
#' # --- Example A: Extract Character Vector ---
#' # Returns standard formatted strings for covariate names
#' generateCovNames(dfCovs, unit_map = unit_map, label_map = label_map)
#'
#' # --- Example B: Relational Data Frame Mapping ---
#' # Safely mutates the data frame, adding locked COVNAME and GROUPNAME factors
#' dfres_updated <- generateCovNames(
#'   dfCovs,
#'   dfres = dfres,
#'   unit_map = unit_map,
#'   label_map = label_map,
#'   group_map = group_map
#' )
#'
#' print(dfres_updated)
#'
#' # --- Example C: Name each covariate once ---
#' # Rows read "Body Weight = 70 kg" and "Male"; the groups are "Body Weight" and "Sex"
#' generateCovNames(
#'   dfCovs,
#'   dfres = dfres,
#'   name_map = name_map,
#'   unit_map = unit_map,
#'   level_map = level_map
#' )
#'
#' # --- Example D: Drop a row ---
#' # NA leaves the SEX = 2 row out of the plot
#' generateCovNames(
#'   dfCovs,
#'   dfres = dfres,
#'   name_map = name_map,
#'   level_map = list(SEX = c("1" = "Male", "2" = NA))
#' )
#'
#' # --- Example E: Merge dummy covariates into one group ---
#' # Three 0/1 genotype dummies become one group with a single reference row:
#' # "2D6 EM", "2D6 UM", "2D6 IM" and "2D6 PM"
#' dfGeno <- data.frame(
#'   COVARIATEGROUPS = rep(c("GENO1N", "GENO3N", "GENO4N"), each = 2),
#'   GENO1N = c(0, 1, -99, -99, -99, -99),
#'   GENO3N = c(-99, -99, 0, 1, -99, -99),
#'   GENO4N = c(-99, -99, -99, -99, 0, 1)
#' )
#' generateCovNames(
#'   dfGeno,
#'   dfres = data.frame(COVNUM = 1:6, PARAMETER = "CL"),
#'   dummy_groups = list("2D6 genotype" = list(
#'     ref = "2D6 EM",
#'     levels = c(GENO1N = "2D6 UM", GENO3N = "2D6 IM", GENO4N = "2D6 PM")
#'   ))
#' )
generateCovNames <- function(dfCovs, dfres = NULL, unit_map = NULL, label_map = NULL, group_map = NULL,
                             print_template = FALSE, name_map = NULL,
                             label_format = "{name} = {value} {unit}", level_map = NULL,
                             dummy_groups = NULL, sep = "_", warn_unused = TRUE) {
  if (!"COVARIATEGROUPS" %in% names(dfCovs)) {
    stop("dfCovs must contain a 'COVARIATEGROUPS' column.", call. = FALSE)
  }
  ## setupDfCovs() records the sep it named the one-hot columns with, as for
  ## setupDfRefRow(); an explicit sep wins
  setup <- attr(dfCovs, "pmxCovSetup")
  if (missing(sep) && !is.null(setup$sep)) sep <- setup$sep
  if (!is.null(level_map) && (!is.list(level_map) || is.null(names(level_map)) ||
    !all(vapply(level_map, function(x) !is.null(names(x)), logical(1))))) {
    stop("level_map must be a named list of vectors named by level, ",
      "e.g. list(SEX = c(\"1\" = \"Male\", \"2\" = \"Female\")).",
      call. = FALSE
    )
  }

  # 1. Extract the covariate value of each row, and the base strings and groups
  groups <- as.character(dfCovs$COVARIATEGROUPS)
  values <- sapply(seq_len(nrow(dfCovs)), function(i) {
    grp <- groups[i]

    if (grp %in% names(dfCovs)) {
      return(as.character(dfCovs[[grp]][i]))
    }

    dummy_cols <- oneHotColumns(names(dfCovs), grp, sep)

    if (length(dummy_cols) == 0) {
      warning(paste("No matching columns found for covariate group:", grp), call. = FALSE)
      return("UNKNOWN")
    }

    suffixes <- as.numeric(substring(dummy_cols, nchar(paste0(grp, sep)) + 1))
    row_vals <- as.numeric(dfCovs[i, dummy_cols, drop = FALSE])

    if (any(row_vals == 1, na.rm = TRUE)) {
      val <- suffixes[which(row_vals == 1)[1]]
    } else {
      val <- min(suffixes, na.rm = TRUE) - 1
    }
    return(as.character(val))
  })
  base_strings <- paste0(groups, "=", values)

  # Check the maps against each other and against dfCovs
  dummy_of <- dummyGroupLookup(dummy_groups, groups)
  checkCovMaps(
    groups, values, base_strings,
    list(name_map = name_map, unit_map = unit_map, group_map = group_map, label_map = label_map),
    level_map, warn_unused
  )

  # The row kept as each dummy group's reference
  ref_rows <- vapply(names(dummy_groups), function(dg) {
    i <- which(groups %in% names(dummy_of)[dummy_of == dg] & values == "0")
    return(if (length(i) > 0) i[1] else NA_integer_)
  }, integer(1))

  # 2. Template Generation Mode
  if (print_template) {
    printCovTemplate(dfCovs, groups, values)
    return(invisible(NULL))
  }

  # 3. Application Mode (Row-level labels)
  res <- sapply(seq_along(base_strings), function(i) {
    b <- base_strings[i]
    g <- groups[i]

    # Label Replacement (Categorical) takes precedence; NA drops the row
    if (!is.null(label_map) && b %in% names(label_map)) {
      if (is.na(label_map[[b]]) || label_map[[b]] != "") {
        return(as.character(label_map[[b]]))
      }
    }

    # Merged dummies: the level of a 1 row, the shared reference of the first 0 row
    if (g %in% names(dummy_of) && values[i] %in% c("0", "1")) {
      dg <- dummy_groups[[dummy_of[[g]]]]
      if (values[i] == "1") {
        return(as.character(dg$levels[[g]]))
      }
      ref <- if (is.null(dg$ref)) NA_character_ else as.character(dg$ref)
      return(if (identical(ref_rows[[dummy_of[[g]]]], i)) ref else NA_character_)
    }

    # Level labels per covariate, likewise
    if (!is.null(level_map) && g %in% names(level_map) && values[i] %in% names(level_map[[g]])) {
      lab <- level_map[[g]][[values[i]]]
      if (is.na(lab) || lab != "") {
        return(as.character(lab))
      }
    }

    # Display name, value and unit
    if (!is.null(name_map)) {
      return(formatCovLabel(label_format, mapEntry(name_map, g, g), values[i], mapEntry(unit_map, g, "")))
    }

    # Unit Appending (Continuous)
    if (!is.null(unit_map) && g %in% names(unit_map)) {
      if (unit_map[[g]] != "") {
        return(paste0(b, " ", unit_map[[g]]))
      }
    }

    return(b)
  })

  # 4. Relational Data Frame Mapping
  if (!is.null(dfres)) {
    if (!"COVNUM" %in% names(dfres)) {
      stop("The provided dfres must contain a 'COVNUM' column to securely map the labels.", call. = FALSE)
    }

    # Leave out the rows of dropped levels
    dfres <- dfres[!is.na(res[dfres$COVNUM]), , drop = FALSE]

    # Map the row labels securely using the row index indicator
    mapped_labels <- res[dfres$COVNUM]
    dfres$COVNAME <- factor(mapped_labels, levels = unique(res[!is.na(res)]))

    # Map the group headers securely
    mapped_groups <- sapply(groups, function(g) {
      if (g %in% names(dummy_of)) {
        return(dummy_of[[g]])
      }
      return(mapEntry(group_map, g, mapEntry(name_map, g, g)))
    })

    # Apply as a factor to lock the group plotting order
    mapped_groups_expanded <- mapped_groups[dfres$COVNUM]
    dfres$GROUPNAME <- factor(mapped_groups_expanded, levels = unique(mapped_groups[!is.na(res)]))

    return(dfres)
  }

  return(as.character(res))
}

## The entry for key in a named map, or default when the map is NULL, has no
## such key, or holds "" for it - a blank entry in a printed template.
mapEntry <- function(map, key, default) {
  if (!is.null(map) && key %in% names(map) && map[[key]] != "") {
    return(map[[key]])
  }
  return(default)
}

## Fill the {name}, {value} and {unit} placeholders of a label format. Without
## a unit, the space before the placeholder is dropped as well.
formatCovLabel <- function(format, name, value, unit) {
  out <- format
  if (unit == "") {
    out <- gsub("\\s*\\{unit\\}", "", out)
  }
  out <- gsub("{name}", name, out, fixed = TRUE)
  out <- gsub("{value}", value, out, fixed = TRUE)
  out <- gsub("{unit}", unit, out, fixed = TRUE)
  return(out)
}

## Check dummy_groups and return the group of each dummy covariate, named by the
## dummy: c(GENO1N = "2D6 genotype", ...). Dummies missing from the covariate
## table are warned about rather than silently ignored.
dummyGroupLookup <- function(dummy_groups, groups) {
  if (is.null(dummy_groups)) {
    return(character(0))
  }
  ok <- is.list(dummy_groups) && !is.null(names(dummy_groups)) && all(names(dummy_groups) != "") &&
    all(vapply(dummy_groups, function(x) {
      is.list(x) && !is.null(names(x$levels)) && all(names(x$levels) != "") &&
        (is.null(x$ref) || length(x$ref) == 1)
    }, logical(1)))
  if (!ok) {
    stop("dummy_groups must be a named list of list(ref = <label>, levels = c(<dummy> = <label>, ...)), ",
      "e.g. list(\"2D6 genotype\" = list(ref = \"EM\", levels = c(GENO1N = \"UM\", GENO4N = \"PM\"))).",
      call. = FALSE
    )
  }

  dummies <- unlist(lapply(dummy_groups, function(x) names(x$levels)), use.names = FALSE)
  dummy_of <- rep(names(dummy_groups), vapply(dummy_groups, function(x) length(x$levels), integer(1)))
  names(dummy_of) <- dummies
  if (anyDuplicated(dummies)) {
    stop("A covariate can be in only one of dummy_groups: ",
      paste(unique(dummies[duplicated(dummies)]), collapse = ", "), ".",
      call. = FALSE
    )
  }
  missing <- setdiff(dummies, groups)
  if (length(missing) > 0) {
    warning("dummy_groups covariates not in dfCovs: ", paste(missing, collapse = ", "), ".", call. = FALSE)
  }
  return(dummy_of)
}

## The one-hot columns of grp: <grp><sep><numeric level>. The numeric level
## keeps GENO from matching GENO1N when sep is "".
oneHotColumns <- function(cols, grp, sep) {
  prefix <- paste0(grp, sep)
  cand <- cols[startsWith(cols, prefix) & nchar(cols) > nchar(prefix)]
  lev <- suppressWarnings(as.numeric(substring(cand, nchar(prefix) + 1)))
  return(cand[!is.na(lev)])
}

## Duplicated keys in any map are an error, since a named vector silently uses
## the first. With warn_unused, keys that match nothing in dfCovs are a warning.
checkCovMaps <- function(groups, values, base_strings, maps, level_map, warn_unused) {
  maps$level_map <- level_map
  for (m in names(maps)) {
    keys <- names(maps[[m]])
    if (anyDuplicated(keys)) {
      stop(m, " has duplicated keys: ", paste(unique(keys[duplicated(keys)]), collapse = ", "), ".",
        call. = FALSE
      )
    }
  }
  for (g in names(level_map)) {
    keys <- names(level_map[[g]])
    if (anyDuplicated(keys)) {
      stop("level_map$", g, " has duplicated levels: ", paste(unique(keys[duplicated(keys)]), collapse = ", "), ".",
        call. = FALSE
      )
    }
  }
  if (!warn_unused) {
    return(invisible(NULL))
  }

  unused <- c(
    unlist(lapply(c("name_map", "unit_map", "group_map", "level_map"), function(m) {
      keys <- setdiff(names(maps[[m]]), groups)
      if (length(keys) > 0) paste0(m, ": ", paste(keys, collapse = ", ")) else NULL
    })),
    if (length(setdiff(names(maps$label_map), base_strings)) > 0) {
      paste0("label_map: ", paste(setdiff(names(maps$label_map), base_strings), collapse = ", "))
    },
    unlist(lapply(intersect(names(level_map), groups), function(g) {
      keys <- setdiff(names(level_map[[g]]), values[groups == g])
      if (length(keys) > 0) paste0("level_map$", g, ": ", paste(keys, collapse = ", ")) else NULL
    }))
  )
  if (length(unused) > 0) {
    warning("Map entries matching nothing in dfCovs (set warn_unused = FALSE to silence):\n  ",
      paste(unused, collapse = "\n  "),
      call. = FALSE
    )
  }
  return(invisible(NULL))
}

## Print name_map, unit_map and level_map with a blank entry per covariate.
## A covariate is taken to be categorical when it is one-hot encoded, or all
## its values are integers 0-9; the rest get a unit_map entry instead.
printCovTemplate <- function(dfCovs, groups, values) {
  u_groups <- unique(groups)
  is_cat <- vapply(u_groups, function(g) {
    v <- suppressWarnings(as.numeric(values[groups == g]))
    return(!g %in% names(dfCovs) || all(!is.na(v) & v == round(v) & v >= 0 & v <= 9))
  }, logical(1))

  printMap <- function(name, entries, fun = "c") {
    cat(name, " <- ", fun, "(\n", sep = "")
    if (length(entries) > 0) cat(paste0("  ", entries, collapse = ",\n"), "\n", sep = "")
    cat(")\n\n")
  }

  cat("# Copy and paste this mapping template into your script:\n\n")
  printMap("name_map", paste0(u_groups, " = \"\""))
  printMap("unit_map", paste0(u_groups[!is_cat], " = \"\""))
  printMap("level_map", vapply(u_groups[is_cat], function(g) {
    levs <- unique(values[groups == g])
    return(paste0(g, " = c(", paste0("\"", levs, "\" = \"\"", collapse = ", "), ")"))
  }, character(1)), fun = "list")
  return(invisible(NULL))
}
